"""plays — the four plays: triggers, entries, exits, conviction.

Design v3 §6 and §11. Plays are mechanical; the agent chooses which are live
and records why (Invariant 3). Nothing here invents an entry outside a play,
and nothing here may modify a play's exit rules — which is why every threshold
in this package is a module constant rather than a config key. A play's shape
belongs to the play. §17 makes that explicit: a fifth play is "a new entry in
plays", not a new file and not a new config section.

**This package does not choose what it looks at.** §5.3's candidate pool is
assembled cheaply by `cli.py` — a Robinhood scan, the earnings calendar,
`edge_events` — and handed over in ``candidates``. Universe size is free;
per-symbol data costs a call each, so the pool arrives already small and plays
judges it rather than searching for it. A name whose data never arrived simply
does not trigger, which is the correct reading of "no signal" and the only one
that does not manufacture a dip out of a missing field.

Two entry points, because §13 gates them differently:

* ``entries`` runs on cycles that may buy, and arbitrates §6.0.
* ``exits`` runs on **every** cycle including overnight ones, and is
  unconditional — §6.5 is a priority list, not a preference.

Plays emits; `guard.py` denies. The two meet on exits 2 and 3, where guard
already refuses *buys* on a drawdown breach or inside the earnings window and
this package emits the *sells* that flatten the book. Guard's own docstring
turns on that division: the drawdown breach is an order denial rather than a
halt precisely so the flatten it demands can still be placed.

This file is the package's public surface: every name the flat module used to
expose at module level is re-exported here unchanged, because `cli.py`,
`reconcile.py` and the test suite all reach into it by attribute
(``plays.would_open``, ``plays._pead``, ``plays.sessions_between``, ...).
"""

