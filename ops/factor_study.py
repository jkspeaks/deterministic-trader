"""Follow-up to ops/placebo_backtest.py: what DOES predict, and when does DIP work?

Run:  uv run ops/factor_study.py   (needs ops/placebo_backtest.py's price cache)

Three questions, all sector-neutral and date-clustered, same data and caveats
(survivorship, no costs) as the placebo backtest:

  A. Volatility-matched placebo: is the +0.3%/trade exit-stack "edge" just
     higher-vol names hitting the fixed 6% target?
  B. Cross-sectional factor ICs: which cheap, price-only factors rank next-8d
     and next-21d returns *within a sector*?
  C. Conditioning: does DIP's excess return depend on market regime, trend
     leadership, or volatility?
"""

from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import eval_selection as es  # noqa: E402
import placebo_backtest as pb  # noqa: E402

ROOT = pb.ROOT
CACHE = ROOT / ".placebo_cache"
SEED = 7
BOOT = 5000


def clustered(diff: np.ndarray, dts: np.ndarray) -> tuple[float, float, float]:
    """`eval_selection.clustered_bootstrap` (S0: one implementation for the
    offline studies and the live control arm), in this file's tuple shape."""
    s = es.clustered_bootstrap(diff.tolist(), [str(d) for d in dts], boot=BOOT, seed=SEED)
    if s is None:
        return np.nan, np.nan, np.nan
    return s["mean"], s["lo"], s["hi"]


def fmt(m, lo, hi) -> str:
    return "n/a" if not np.isfinite(m) else f"{m:+.2%} [{lo:+.2%}, {hi:+.2%}]"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # the report prints a minus sign cp1252 lacks
    px = pickle.loads((CACHE / "prices.pkl").read_bytes())
    import yfinance as yf

    spy = yf.download("SPY", start=pb.START, auto_adjust=True, progress=False)
    spy = spy["Close"].squeeze() if "Close" in spy else spy.squeeze()

    uni = json.loads((ROOT / "data" / "universe.json").read_text())
    sector = {r["symbol"]: r["sector"] for r in uni["cross_check"]}
    syms = [s for s in sorted(sector) if s in px]
    dates = sorted(set().union(*(set(px[s].index) for s in syms)))
    N = len(dates)
    spy = spy.reindex(dates).ffill()

    C = np.full((N, len(syms)), np.nan)
    IND = {}
    for j, s in enumerate(syms):
        d = px[s].reindex(dates).ffill(limit=3)
        if d["Close"].isna().mean() > 0.5:
            continue
        ind = pb.indicators(d)
        IND[s] = ind
        C[:, j] = ind["c"]
    keep = [j for j, s in enumerate(syms) if s in IND]
    syms = [syms[j] for j in keep]
    C = C[:, keep]
    sec = np.array([sector[s] for s in syms])
    S = len(syms)

    def lag(a, k):
        o = np.full_like(a, np.nan)
        o[k:] = a[:-k]
        return o

    ret = lambda k: C / lag(C, k) - 1  # noqa: E731
    hi52 = pd.DataFrame(C).rolling(252, min_periods=200).max().to_numpy()
    vol60 = pd.DataFrame(np.log(C / lag(C, 1))).rolling(60).std().to_numpy()
    rsi = np.column_stack([IND[s]["rsi"] for s in syms])
    atrp = np.column_stack([IND[s]["atr"] / IND[s]["c"] for s in syms])
    sma200 = np.column_stack([IND[s]["sma200"] for s in syms])

    def sec_demean(x):
        out = x.copy()
        for g in np.unique(sec):
            m = sec == g
            out[:, m] = x[:, m] - np.nanmean(x[:, m], axis=1, keepdims=True)
        return out

    F = {
        "mom_12_1 (higher=better)": lag(C, 21) / lag(C, 252) - 1,
        "mom_6_1": lag(C, 21) / lag(C, 126) - 1,
        "rs_3m vs sector": sec_demean(ret(63)),
        "rs_1m vs sector": sec_demean(ret(21)),
        "near 52w high": C / hi52,
        "low volatility (60d)": -vol60,
        "1w reversal (neg 5d ret)": -ret(5),
        "oversold (neg RSI14)": -rsi,
        "above 200d (C/SMA200)": C / sma200,
    }
    out = ["# Factor study and DIP conditioning (2026-10-04)\n",
           f"Generated by `ops/factor_study.py`. {S} current S&P 500 names, {dates[0].date()} to {dates[-1].date()}. "
           "Sector-neutral: forward returns are net of the same-day mean of the name's sector. "
           "IC = daily cross-sectional Spearman; sampled every h days (h = horizon) so samples do not overlap; "
           "t = mean IC / se.\n"]

    for h in (8, 21):
        fwd = np.full_like(C, np.nan)
        fwd[:-h] = C[h:] / C[:-h] - 1
        # Sector-neutral over the whole cross-section (as before); the IC and
        # the quintile spread are `eval_selection.cross_section`, the function
        # the live snapshot panel is scored by (S0).
        y = sec_demean(fwd)
        rows = []
        for name, f in F.items():
            ics, spreads = [], []
            for t in range(260, N - h, h):
                stat = es.cross_section(f[t].tolist(), y[t].tolist(), min_names=100)
                if stat is None:
                    continue
                ics.append(stat["ic"])
                spreads.append(stat["spread"])
            summary = es.ic_summary(ics)
            rows.append((name, summary["mean"], summary["t"],
                         es.mean(spreads), es.t_stat(spreads), summary["n"]))
        out.append(f"\n## B. Sector-neutral factor ICs, {h}-session forward return\n")
        out.append("| factor | mean IC | t | top-minus-bottom quintile | t | n dates |\n|---|---|---|---|---|---|\n")
        for r in sorted(rows, key=lambda r: -abs(r[2])):
            out.append(f"| {r[0]} | {r[1]:+.4f} | {r[2]:+.1f} | {r[3]:+.2%} | {r[4]:+.1f} | {r[5]} |\n")

    # --- DIP events -------------------------------------------------------
    retstack = np.column_stack([pb.trade_returns(IND[s]) for s in syms])
    fwd8 = np.full_like(C, np.nan)
    fwd8[:-8] = C[8:] / C[:-8] - 1
    sma20 = np.column_stack([IND[s]["sma20"] for s in syms])
    with np.errstate(invalid="ignore"):
        trend = C >= 0.97 * sma200
        sig = (rsi <= 30) & trend & (C < sma20)
    spy_c = spy.to_numpy()
    spy200 = pd.Series(spy_c).rolling(200).mean().to_numpy()
    spy_rv = pd.Series(np.log(spy_c)).diff().rolling(20).std().to_numpy() * np.sqrt(252)
    spy_dd = spy_c / pd.Series(spy_c).rolling(252, min_periods=200).max().to_numpy() - 1
    mom121, rs3m, near_hi = F["mom_12_1 (higher=better)"], F["rs_3m vs sector"], F["near 52w high"]
    rng = np.random.default_rng(SEED)

    ev = []
    for j in range(S):
        last = -10**9
        for i in np.flatnonzero(sig[:, j]):
            if i - last <= 8 or not np.isfinite(retstack[i, j]) or not np.isfinite(fwd8[i, j]):
                continue
            last = i
            peers = np.flatnonzero((sec == sec[j]) & ~sig[i] & np.isfinite(retstack[i]) & np.isfinite(atrp[i]))
            peers = peers[peers != j]
            if len(peers) < 8 or not np.isfinite(atrp[i, j]):
                continue
            # vol-matched: peers within +/-25% of this name's ATR%, else nearest 8
            dist = np.abs(atrp[i, peers] / atrp[i, j] - 1)
            vm = peers[dist <= 0.25]
            if len(vm) < 4:
                vm = peers[np.argsort(dist)[:8]]
            pk = rng.choice(peers, 200)
            vk = rng.choice(vm, 200)
            ev.append(dict(
                date=dates[i], year=dates[i].year, stk=retstack[i, j], fwd=fwd8[i, j],
                p1=np.nanmean(retstack[i, pk]), pv=np.nanmean(retstack[i, vk]),
                f1=np.nanmean(fwd8[i, pk]), fv=np.nanmean(fwd8[i, vk]),
                mom=mom121[i, j], rs=rs3m[i, j], hi=near_hi[i, j], atrp=atrp[i, j],
                spy_above=bool(spy_c[i] >= spy200[i]) if np.isfinite(spy200[i]) else None,
                spy_rv=spy_rv[i], spy_dd=spy_dd[i],
            ))
    e = pd.DataFrame(ev)
    d = e.date.to_numpy()

    out.append(f"\n## A. Volatility-matched placebo (N={len(e)})\n")
    out.append("| comparison | exit-stack edge [95% CI] | plain 8d fwd edge [95% CI] |\n|---|---|---|\n")
    out.append(f"| DIP − random sector peer | {fmt(*clustered((e.stk - e.p1).to_numpy(), d))} | {fmt(*clustered((e.fwd - e.f1).to_numpy(), d))} |\n")
    out.append(f"| DIP − vol-matched sector peer | {fmt(*clustered((e.stk - e.pv).to_numpy(), d))} | {fmt(*clustered((e.fwd - e.fv).to_numpy(), d))} |\n")
    out.append(f"\nMean ATR% of DIP names {e.atrp.mean():.2%}; target-hit rate (stack return >= 6%): {(e.stk >= 0.0599).mean():.0%}.\n")

    def cond(title, key, bins=None, labels=None, cut=None):
        s = cut if cut is not None else pd.qcut(e[key], 3, labels=["low", "mid", "high"])
        out.append(f"\n### {title}\n| bucket | N | exit-stack edge vs vol-matched [95% CI] | 8d fwd edge vs random peer [95% CI] |\n|---|---|---|---|\n")
        for b in [x for x in pd.unique(s.dropna())]:
            m = (s == b).to_numpy()
            out.append(f"| {b} | {m.sum()} | {fmt(*clustered((e.stk - e.pv).to_numpy()[m], d[m]))} | {fmt(*clustered((e.fwd - e.f1).to_numpy()[m], d[m]))} |\n")

    out.append("\n## C. Does DIP's edge depend on context?\n")
    cond("12-1 month momentum of the dipping name (tercile)", "mom")
    cond("3-month return vs own sector (tercile)", "rs")
    cond("Distance from 52-week high (tercile; high = near the high)", "hi")
    cond("Name volatility, ATR% (tercile)", "atrp")
    cond("SPY vs its 200-day", None, cut=e.spy_above.map({True: "SPY above 200d", False: "SPY below 200d"}))
    cond("SPY 20d realized vol (tercile)", "spy_rv")
    cond("SPY drawdown from 52w high (tercile; low = deeper drawdown)", "spy_dd")
    cond("Year", None, cut=e.year.astype(str))
    # Not `docs/`: the dated report there is a verdict and is not regenerated
    # in place.
    (CACHE / "factor-study.md").write_text("".join(out), encoding="utf-8")
    print("".join(out))


if __name__ == "__main__":
    main()
